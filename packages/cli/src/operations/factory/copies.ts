import { chmodSync, existsSync, lstatSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { assertManagedPathHasNoSymlinks } from "../../utils";
import type { StoreDatabase } from "../../store/database";
import {
  listFactoryMachineTools,
  listFactoryWorkflowBindings,
  readFactoryPlanRevision,
  type FactoryMachineToolRecord,
  type FactoryPlanRevisionRecord,
  type FactoryWorkflowBindingRecord,
} from "../../store/factory-store";

/**
 * W30 R0 P2 local factory copies (PRD 53 R-FACTORY-25, PRD 38 R-DB-6, PRD 21
 * R-LOCAL-STATE-2).
 *
 * Make Docs writes generated, read-only copies of the saved factory setup to
 * `.make-docs/factory/`, from the Store only. Each file starts with a note
 * that it is generated and that edits are lost. The folder holds its own
 * `.gitignore`, so git ignores every file in it. No copy holds a grant: the
 * writer never reads the grants table. Make Docs never reads a copy as input:
 * this module only writes and removes files, and `isProtectedContentPath`
 * keeps the folder out of every content scan.
 */

export const FACTORY_COPIES_RELATIVE_PATH = ".make-docs/factory";

/** The first line of every Markdown copy. */
export const FACTORY_COPY_NOTE =
  "> Generated by Make Docs from the Store. Do not edit this file: Make Docs writes it again, and your edits are lost. Make Docs never reads this file.";

/** The folder's own ignore file, so the copies stay out of git without a change to the project's `.gitignore`. */
export const FACTORY_COPIES_GITIGNORE = "*\n";

export const FACTORY_TOOLS_COPY_NAME = "tools.md";
export function factoryWorkflowCopyName(workflowName: string): string {
  return `workflow-${workflowName}.md`;
}

export interface FactoryCopiesResult {
  folder: string;
  /** File names written, sorted. */
  written: string[];
  /** Earlier copies that the Store no longer has, removed. */
  removed: string[];
}

function cell(value: string): string {
  return value.replaceAll("|", "\\|");
}

function toolsCopy(tools: readonly FactoryMachineToolRecord[]): string {
  const lines = [FACTORY_COPY_NOTE, "", "# Factory Machine Tools", "", "These are the agent tools that factory setup found on this machine. Every project on this machine shares this list.", ""];
  if (tools.length === 0) {
    lines.push("No tool is saved yet.", "");
    return lines.join("\n");
  }
  lines.push("| Tool ID | Kind | Label | State | Reported version | Capabilities |", "| --- | --- | --- | --- | --- | --- |");
  for (const tool of tools) {
    lines.push(`| \`${tool.toolId}\` | ${tool.kind} | ${cell(tool.label)} | ${tool.state} | ${tool.reportedVersion ? cell(tool.reportedVersion) : "not reported"} | ${tool.capabilities.map((id) => `\`${id}\``).join(", ") || "none"} |`);
  }
  lines.push("", "## Capability Proofs", "");
  const proofs = tools.flatMap((tool) => tool.proofs.map((proof) => ({ tool: tool.toolId, ...proof })));
  if (proofs.length === 0) {
    lines.push("No proof is saved yet.", "");
  } else {
    lines.push("| Tool ID | Capability | Result | Tool version | Proof time | How it was proved | Does not cover |", "| --- | --- | --- | --- | --- | --- | --- |");
    for (const proof of proofs) {
      lines.push(`| \`${proof.tool}\` | \`${proof.capabilityId}\` | ${proof.result} | ${proof.toolVersion ? cell(proof.toolVersion) : "not reported"} | ${proof.provedAt} | ${cell(proof.method)} | ${proof.notCovered.map(cell).join("; ") || "nothing listed"} |`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

function workflowCopy(binding: FactoryWorkflowBindingRecord, latest: FactoryPlanRevisionRecord | null): string {
  const lines = [FACTORY_COPY_NOTE, "", `# Factory Workflow \`${binding.workflowName}\``, "", `Saved readiness: ${binding.readiness}.`, ""];
  lines.push("## Saved Binding", "", "| Role | Tool ID |", "| --- | --- |");
  const roles = Object.entries(binding.roles);
  for (const [role, tool] of roles) lines.push(`| ${role} | \`${tool}\` |`);
  if (roles.length === 0) lines.push("| none | none |");
  // The channel kind and the integration owner live only in config (owner decision 2026-11-23), so the
  // printout reads them from the latest resolved plan, which joined the config entry.
  const definition = latest ? ((JSON.parse(latest.planJson) as { definition?: { humanChannel?: unknown; integrationOwner?: unknown } }).definition ?? {}) : null;
  const fromPlan = (value: unknown, none: string) => (definition === null ? "not in a saved plan yet" : typeof value === "string" ? value : none);
  lines.push(
    "",
    `- Wake method: ${binding.wakeMethod}${binding.wakeRef ? ` (${binding.wakeRef})` : ""}.`,
    `- Human channel: ${fromPlan(definition?.humanChannel, "none")}${binding.channelRef ? ` (${binding.channelRef})` : ""}.`,
    `- Working-copy method: ${binding.worktreeMethod}.`,
    `- Integration owner: ${fromPlan(definition?.integrationOwner, "none")}.`,
    `- Accepted known losses: ${knownLossesLine(binding.knownLosses)}`,
    "",
    "## Resolved Plan",
    "",
  );
  if (!latest) {
    lines.push("No plan revision is saved yet.", "");
    return lines.join("\n");
  }
  const readyLine = binding.readyRevision === null
    ? "No revision is the `ready` revision yet."
    : binding.readyRevision === latest.revision
      ? "This is the `ready` revision."
      : `This is not the \`ready\` revision. The \`ready\` revision is ${binding.readyRevision}.`;
  lines.push(
    `Latest plan revision: ${latest.revision}. ${readyLine}`,
    "",
    `- Plan digest: \`${latest.planDigest}\``,
    `- Config digest: \`${latest.configDigest}\``,
    `- Binding digest: \`${latest.bindingDigest}\``,
    `- Saved: ${latest.createdAt}`,
    "",
    "```json",
    JSON.stringify(JSON.parse(latest.planJson), null, 2),
    "```",
    "",
  );
  return lines.join("\n");
}

function writeReadOnly(file: string, content: string): void {
  if (existsSync(file)) {
    if (!lstatSync(file).isFile()) throw new Error(`${file} is not a regular file, so Make Docs does not replace it.`);
    chmodSync(file, 0o644);
  }
  writeFileSync(file, content, { encoding: "utf8", mode: 0o644 });
  chmodSync(file, 0o444);
}

/**
 * The accepted known losses as one line that ends with one full stop. A loss that ends with a full stop
 * gets no second one. An ellipsis at the end of a loss stays as it is.
 */
export function knownLossesLine(knownLosses: readonly string[]): string {
  if (knownLosses.length === 0) return "none.";
  const joined = knownLosses.map((loss) => loss.replace(/(?<!\.)\.$/, "")).join("; ");
  return joined.endsWith(".") ? joined : `${joined}.`;
}

/**
 * Write the copies of one project's saved factory setup (T9, T21). It reads
 * the machine tools, the project's workflow bindings, and each workflow's
 * latest plan revision from the Store. It never reads a grant. A file that
 * the Store no longer backs is removed. Edits to a copy are lost here.
 */
export function writeFactoryCopies(db: StoreDatabase, projectRoot: string, projectId: string): FactoryCopiesResult {
  // Read everything first, so a refused project ID writes nothing. The project ID is explicit, never taken from the folder.
  const bindings = listFactoryWorkflowBindings(db, projectId);
  assertManagedPathHasNoSymlinks(projectRoot, FACTORY_COPIES_RELATIVE_PATH);
  const folder = path.join(projectRoot, ...FACTORY_COPIES_RELATIVE_PATH.split("/"));
  const files = new Map<string, string>();
  files.set(".gitignore", FACTORY_COPIES_GITIGNORE);
  files.set(FACTORY_TOOLS_COPY_NAME, toolsCopy(listFactoryMachineTools(db)));
  for (const binding of bindings) {
    files.set(factoryWorkflowCopyName(binding.workflowName), workflowCopy(binding, readFactoryPlanRevision(db, projectId, binding.workflowName)));
  }
  mkdirSync(folder, { recursive: true });
  const removed: string[] = [];
  for (const name of readdirSync(folder)) {
    if (files.has(name)) continue;
    const entry = path.join(folder, name);
    if (!lstatSync(entry).isFile()) continue;
    chmodSync(entry, 0o644);
    rmSync(entry, { force: true });
    removed.push(name);
  }
  for (const [name, content] of files) writeReadOnly(path.join(folder, name), content);
  return { folder, written: [...files.keys()].sort(), removed: removed.sort() };
}
