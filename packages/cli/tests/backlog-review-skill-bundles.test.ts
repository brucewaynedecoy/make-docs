import { execFileSync, spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { pathToFileURL } from "node:url";

import { afterEach, describe, expect, test } from "vitest";

import {
  boundedProjectLeadExcerpt,
  collectProjectLeadContext,
  parseProjectLeadContextArgs,
  ProjectLeadContextUsageError,
} from "../src/operations/work/backlog/project-lead-context";
import {
  BacklogReportFileUsageError,
  parseBacklogReportFileArgs,
  resolveBacklogReportFilePaths,
} from "../src/operations/work/backlog/report-file";
import { mixedPortfolioFixture } from "./fixtures/backlog-contract";

// W34 R0 P3 (PRD 08 R-SKILL-BUNDLE-7, PRD 51 R-BACKLOG-SKILL-21): every file in the
// backlog-review Skill `scripts/` folder is a generated bundle of CLI source.
// @ts-expect-error Authoring-only JavaScript build helper.
const generator = await import("../scripts/build-backlog-presentation.mjs");
type Script = { flag: string; path: string; build: () => string };
const scripts = generator.portableBacklogSkillScripts as Script[];
const SKILL_ROOT = path.resolve(generator.portableBacklogSkillScriptsDir as string, "..");

const roots: string[] = [];
const temporaryRoot = (): string => {
  const root = mkdtempSync(path.join(os.tmpdir(), "make-docs-backlog-bundles-"));
  roots.push(root);
  return root;
};
afterEach(() => {
  for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true });
});

describe("backlog-review Skill bundles", () => {
  test("lists exactly the files in the Skill scripts folder", () => {
    expect(scripts.map((script) => path.basename(script.path)).sort()).toEqual(
      readdirSync(generator.portableBacklogSkillScriptsDir).filter((name) => !name.startsWith(".")).sort(),
    );
    expect(scripts.map((script) => path.basename(script.path))).toEqual([
      "report-contract.mjs",
      "agent-contract.mjs",
      "render-report.mjs",
      "collect-project-lead-context.mjs",
    ]);
  });

  test.each(scripts.map((script) => [path.basename(script.path), script] as const))(
    "%s matches a fresh build byte for byte",
    (_name, script) => {
      const fresh = Buffer.from(script.build(), "utf8");
      expect(readFileSync(script.path).equals(fresh)).toBe(true);
      expect(fresh.toString("utf8")).toMatch(
        new RegExp(`^(?:#!/usr/bin/env node\\n)?// Generated by packages/cli/scripts/build-backlog-presentation\\.mjs${script.flag ? ` ${script.flag}` : ""}\\. Do not edit\\.\\n`),
      );
    },
  );

  test("the shared check passes, then fails when one byte changes in any file", () => {
    expect(generator.checkPortableBacklogSkillScripts()).toEqual([]);
    for (const target of scripts) {
      const readFile = (file: string): Buffer => {
        const bytes = readFileSync(file);
        if (file !== target.path) return bytes;
        const changed = Buffer.from(bytes);
        const index = changed.length - 2;
        changed[index] = changed[index] === 0x20 ? 0x21 : 0x20;
        return changed;
      };
      expect(generator.checkPortableBacklogSkillScripts({ readFile })).toEqual([
        { path: target.path, problem: "bytes-differ" },
      ]);
    }
  });

  test("the shared check fails a missing file and a hand-written extra file", () => {
    const missing = scripts[3]!.path;
    const readFile = (file: string): Buffer => {
      if (file === missing) throw new Error("ENOENT");
      return readFileSync(file);
    };
    const listScripts = (): string[] => [...readdirSync(generator.portableBacklogSkillScriptsDir), "helper.mjs"];
    expect(generator.checkPortableBacklogSkillScripts({ readFile, listScripts })).toEqual([
      { path: missing, problem: "missing" },
      { path: path.join(generator.portableBacklogSkillScriptsDir, "helper.mjs"), problem: "not-generated" },
    ]);
  });

  test("the two executable scripts import only Node built-ins and the sibling report contract", () => {
    for (const name of ["render-report.mjs", "collect-project-lead-context.mjs"]) {
      const body = readFileSync(path.join(SKILL_ROOT, "scripts", name), "utf8");
      const specifiers = [...body.matchAll(/^import\s[^;]*?from\s+"([^"]+)";$/gm)].map((match) => match[1]!);
      expect(specifiers.length).toBeGreaterThan(0);
      for (const specifier of specifiers) {
        expect(specifier.startsWith("node:") || specifier === "./report-contract.mjs").toBe(true);
      }
      expect(body).not.toMatch(/\brequire\(|import\(/);
    }
    expect(readFileSync(path.join(SKILL_ROOT, "scripts/render-report.mjs"), "utf8")).toContain(
      'import { renderBacklogStaticHtml } from "./report-contract.mjs";',
    );
  });

  test("each bundle runs from a Skill copy with no CLI, node_modules, Store, or network", async () => {
    const root = temporaryRoot();
    const copy = path.join(root, "backlog-review");
    cpSync(SKILL_ROOT, copy, { recursive: true });
    expect(existsSync(path.join(root, "node_modules"))).toBe(false);
    const env = { PATH: process.env.PATH ?? "", MAKE_DOCS_HOME: path.join(root, "no-store"), NODE_PATH: "" };

    const project = path.join(root, "project");
    mkdirSync(path.join(project, "docs/prd"), { recursive: true });
    writeFileSync(path.join(project, "docs/prd/01-product-overview.md"), "# Overview\n\n## Purpose\n\nAurora keeps notes.\n");
    writeFileSync(path.join(project, "docs/prd/00-index.md"), "# Index\n\n## Current Status\n\nW1 is active.\n");
    const packet = JSON.parse(execFileSync(process.execPath, [
      path.join(copy, "scripts/collect-project-lead-context.mjs"), "--target-root", project,
    ], { cwd: root, env, encoding: "utf8" }));
    expect(packet.sources.map((source: { id: string }) => source.id)).toEqual(["purpose-product-overview", "current-status-prd-index"]);

    const input = path.join(root, "report.json");
    const output = path.join(root, "report.html");
    writeFileSync(input, JSON.stringify(mixedPortfolioFixture.report));
    execFileSync(process.execPath, [path.join(copy, "scripts/render-report.mjs"), "--input", input, "--output", output], { cwd: root, env });
    expect(readFileSync(output, "utf8")).toContain('<script id="backlog-report-data" type="application/json">');

    for (const name of ["agent-contract.mjs", "report-contract.mjs"]) {
      const result = spawnSync(process.execPath, ["--input-type=module", "-e", `await import(${JSON.stringify(pathToFileURL(path.join(copy, "scripts", name)).href)});`], { cwd: root, env, encoding: "utf8" });
      expect(result.stderr).toBe("");
      expect(result.status).toBe(0);
    }
    expect(existsSync(env.MAKE_DOCS_HOME)).toBe(false);
  });
});

describe("project-lead context source", () => {
  test("parses arguments and refuses bad input with a usage error", () => {
    expect(parseProjectLeadContextArgs(["--target-root", "x", "--current-record", "a"])).toEqual({ targetRoot: "x", currentRecords: ["a"] });
    for (const args of [[], ["--target-root"], ["--bogus"], ["--target-root", "x", ...Array(4).fill(["--current-record", "a"]).flat()]]) {
      expect(() => parseProjectLeadContextArgs(args)).toThrow(ProjectLeadContextUsageError);
    }
  });

  test("refuses unsafe record paths before reading", () => {
    const root = temporaryRoot();
    for (const record of ["../outside", "/absolute", "docs\\work\\a"]) {
      expect(() => collectProjectLeadContext({ targetRoot: root, currentRecords: [record] })).toThrow(ProjectLeadContextUsageError);
    }
    expect(collectProjectLeadContext({ targetRoot: root, currentRecords: [] })).toEqual({ schemaVersion: 1, targetRoot: root, sources: [] });
  });

  test("bounds excerpts to two blocks and about 2,000 characters", () => {
    expect(boundedProjectLeadExcerpt("one\n\ntwo\n\nthree")).toBe("one\n\ntwo");
    const long = "Sentence. ".repeat(400);
    const excerpt = boundedProjectLeadExcerpt(long);
    expect(excerpt.length).toBeLessThanOrEqual(2_001);
    expect(excerpt.endsWith("…")).toBe(true);
    expect(boundedProjectLeadExcerpt("x".repeat(2_600))).toBe(`${"x".repeat(2_000)}…`);
  });
});

describe("report file source", () => {
  test("parses arguments and refuses bad input with a usage error", () => {
    expect(parseBacklogReportFileArgs(["--input", "a.json", "--output", "b.html", "--force"])).toEqual({ input: "a.json", output: "b.html", force: true });
    for (const args of [[], ["--input"], ["--input", "a.json"], ["--bogus"]]) {
      expect(() => parseBacklogReportFileArgs(args)).toThrow(BacklogReportFileUsageError);
    }
  });

  test("checks the selected paths before any read", () => {
    const root = temporaryRoot();
    const existing = path.join(root, "existing.html");
    writeFileSync(existing, "");
    expect(() => resolveBacklogReportFilePaths({ input: "a.json", output: path.join(root, "x.txt"), force: false })).toThrow("must end in .html");
    expect(() => resolveBacklogReportFilePaths({ input: existing, output: existing, force: true })).toThrow("must be different");
    expect(() => resolveBacklogReportFilePaths({ input: "a.json", output: existing, force: false })).toThrow("already exists");
    expect(resolveBacklogReportFilePaths({ input: "a.json", output: existing, force: true }).outputPath).toBe(existing);
  });
});
