import { buildSync } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = fileURLToPath(new URL("../../../", import.meta.url));
export const portableBacklogPresentationPath = path.join(repoRoot, "packages/skills/backlog-review/scripts/report-contract.mjs");
export const portableBacklogAgentContractPath = path.join(repoRoot, "packages/skills/backlog-review/scripts/agent-contract.mjs");

/** Authoring only. Installed Skills use the generated file with Node built-ins. */
export function buildPortableBacklogPresentation() {
  const require = createRequire(import.meta.url);
  const license = readFileSync(path.join(path.dirname(require.resolve("zod/package.json")), "LICENSE"), "utf8");
  const result = buildSync({
    absWorkingDir: repoRoot,
    entryPoints: ["packages/cli/src/operations/work/backlog/presentation.ts"],
    bundle: true, platform: "node", target: "node24", format: "esm", write: false,
    minifySyntax: true, minifyWhitespace: true, legalComments: "inline",
    // Lower multiline literals without changing the string values they contain.
    supported: { "template-literal": false },
    banner: { js: `// Generated by packages/cli/scripts/build-backlog-presentation.mjs. Do not edit.\n/* Bundled Zod license:\n${license.trim()}\n*/` },
  });
  return result.outputFiles[0].text;
}

/** Separate portable agent contract. Existing report-contract exports/bytes stay unchanged. */
export function buildPortableBacklogAgentContract() {
  const require = createRequire(import.meta.url);
  const license = readFileSync(path.join(path.dirname(require.resolve("zod/package.json")), "LICENSE"), "utf8");
  return buildSync({
    absWorkingDir: repoRoot, entryPoints: ["packages/cli/src/operations/work/backlog/agent-contracts.ts"],
    bundle: true, platform: "node", target: "node24", format: "esm", write: false,
    minifySyntax: true, minifyWhitespace: true, legalComments: "inline", supported: { "template-literal": false },
    banner: { js: `// Generated by packages/cli/scripts/build-backlog-presentation.mjs --agent. Do not edit.\n/* Bundled Zod license:\n${license.trim()}\n*/` },
  }).outputFiles[0].text;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const agent = process.argv.includes("--agent");
  const target = agent ? portableBacklogAgentContractPath : portableBacklogPresentationPath;
  writeFileSync(target, agent ? buildPortableBacklogAgentContract() : buildPortableBacklogPresentation(), "utf8");
  console.log(target);
}
