import { buildSync } from "esbuild";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = fileURLToPath(new URL("../../../", import.meta.url));
const backlogSourceDir = path.join(repoRoot, "packages/cli/src/operations/work/backlog");
const skillScriptsDir = path.join(repoRoot, "packages/skills/backlog-review/scripts");
export const portableBacklogSkillScriptsDir = skillScriptsDir;
export const portableBacklogPresentationPath = path.join(skillScriptsDir, "report-contract.mjs");
export const portableBacklogAgentContractPath = path.join(skillScriptsDir, "agent-contract.mjs");
export const portableBacklogRenderReportPath = path.join(skillScriptsDir, "render-report.mjs");
export const portableBacklogProjectLeadContextPath = path.join(skillScriptsDir, "collect-project-lead-context.mjs");

/** Authoring only. Installed Skills use the generated file with Node built-ins. */
export function buildPortableBacklogPresentation() {
  const require = createRequire(import.meta.url);
  const license = readFileSync(path.join(path.dirname(require.resolve("zod/package.json")), "LICENSE"), "utf8");
  const result = buildSync({
    absWorkingDir: repoRoot,
    entryPoints: ["packages/cli/src/operations/work/backlog/presentation.ts"],
    bundle: true, platform: "node", target: "node24", format: "esm", write: false,
    minifySyntax: true, minifyWhitespace: true, legalComments: "inline",
    // Lower multiline literals without changing the string values they contain.
    supported: { "template-literal": false },
    banner: { js: `// Generated by packages/cli/scripts/build-backlog-presentation.mjs. Do not edit.\n/* Bundled Zod license:\n${license.trim()}\n*/` },
  });
  return result.outputFiles[0].text;
}

/** Separate portable agent contract. Existing report-contract exports/bytes stay unchanged. */
export function buildPortableBacklogAgentContract() {
  const require = createRequire(import.meta.url);
  const license = readFileSync(path.join(path.dirname(require.resolve("zod/package.json")), "LICENSE"), "utf8");
  return buildSync({
    absWorkingDir: repoRoot, entryPoints: ["packages/cli/src/operations/work/backlog/agent-contracts.ts"],
    bundle: true, platform: "node", target: "node24", format: "esm", write: false,
    minifySyntax: true, minifyWhitespace: true, legalComments: "inline", supported: { "template-literal": false },
    banner: { js: `// Generated by packages/cli/scripts/build-backlog-presentation.mjs --agent. Do not edit.\n/* Bundled Zod license:\n${license.trim()}\n*/` },
  }).outputFiles[0].text;
}

/**
 * Build one small executable Skill script. The entry is a two-line call into CLI source,
 * so the logic has one home. The output stays readable, because agents may read it.
 */
function buildPortableBacklogScript({ flag, sourcefile, contents, external = [] }) {
  return buildSync({
    absWorkingDir: repoRoot,
    stdin: { contents, resolveDir: backlogSourceDir, sourcefile, loader: "ts" },
    bundle: true, platform: "node", target: "node24", format: "esm", write: false,
    legalComments: "inline", external,
    banner: { js: `#!/usr/bin/env node\n// Generated by packages/cli/scripts/build-backlog-presentation.mjs ${flag}. Do not edit.` },
  }).outputFiles[0].text;
}

/** `scripts/render-report.mjs` from `report-file.ts`. */
export function buildPortableBacklogRenderReport() {
  return buildPortableBacklogScript({
    flag: "--render",
    sourcefile: "generated-entry:render-report",
    // The renderer comes from the sibling report-contract.mjs bundle, not a second copy.
    contents: 'import { renderBacklogStaticHtml } from "./report-contract.mjs";\nimport { runRenderReportScript } from "./report-file.js";\n'
      + "runRenderReportScript(process.argv.slice(2), import.meta.url, renderBacklogStaticHtml);\n",
    external: ["./report-contract.mjs"],
  });
}

/** `scripts/collect-project-lead-context.mjs` from `project-lead-context.ts`. */
export function buildPortableBacklogProjectLeadContext() {
  return buildPortableBacklogScript({
    flag: "--collector",
    sourcefile: "generated-entry:collect-project-lead-context",
    contents: 'import { runCollectProjectLeadContextScript } from "./project-lead-context.js";\nrunCollectProjectLeadContextScript(process.argv.slice(2));\n',
  });
}

/** Every file in the backlog-review Skill `scripts/` folder, with its fresh build. */
export const portableBacklogSkillScripts = [
  { flag: "", path: portableBacklogPresentationPath, build: buildPortableBacklogPresentation },
  { flag: "--agent", path: portableBacklogAgentContractPath, build: buildPortableBacklogAgentContract },
  { flag: "--render", path: portableBacklogRenderReportPath, build: buildPortableBacklogRenderReport },
  { flag: "--collector", path: portableBacklogProjectLeadContextPath, build: buildPortableBacklogProjectLeadContext },
];

/**
 * Compare each Skill script with a fresh build. Returns the paths whose bytes differ
 * and any file in the Skill `scripts/` folder that no build produces. Empty means all match.
 */
export function checkPortableBacklogSkillScripts({ readFile = (file) => readFileSync(file), listScripts = () => readdirSync(skillScriptsDir) } = {}) {
  const problems = [];
  for (const script of portableBacklogSkillScripts) {
    const expected = Buffer.from(script.build(), "utf8");
    let actual = null;
    try { actual = readFile(script.path); } catch { actual = null; }
    if (!actual || !Buffer.from(actual).equals(expected)) problems.push({ path: script.path, problem: actual ? "bytes-differ" : "missing" });
  }
  const known = new Set(portableBacklogSkillScripts.map((script) => path.basename(script.path)));
  for (const name of listScripts()) {
    if (name.startsWith(".")) continue; // Finder and other tools add hidden files such as .DS_Store.
    if (!known.has(name)) problems.push({ path: path.join(skillScriptsDir, name), problem: "not-generated" });
  }
  return problems;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const flags = process.argv.slice(2);
  const all = flags.includes("--all");
  const selected = portableBacklogSkillScripts.filter((script) =>
    all || (script.flag === "" ? !flags.some((flag) => flag !== "--all") : flags.includes(script.flag)));
  for (const script of selected) {
    writeFileSync(script.path, script.build(), "utf8");
    console.log(script.path);
  }
}
